"""Generate franka_env_cfg.py from the official policyik_sim/tasks/env_cfg.py by mechanical substitution only
(robot names, base env, pool paths, absolute imports), plus a short Franka-specific block. Keeps the PolicyIK
observation/reward/action design byte-identical otherwise; `diff` the two files to audit."""
import re
src = open("policyik_sim/tasks/env_cfg.py").read()
subs = [
    ("from openarm.tasks.manager_based.openarm_manipulation.unimanual.reach.config.joint_pos_env_cfg import (\n"
     "    OpenArmReachEnvCfg,\n    OpenArmReachEnvCfg_PLAY,\n)",
     "from isaaclab_tasks.manager_based.manipulation.reach.config.franka.joint_pos_env_cfg import (\n"
     "    FrankaReachEnvCfg,\n    FrankaReachEnvCfg_PLAY,\n)"),
    ("from . import mdp", "from policyik_sim.tasks import mdp"),
    ("from .actions import", "from policyik_sim.tasks.actions import"),
    ("from .sampling import", "import policyik_sim.tasks.sampling as _sampling\nfrom policyik_sim.tasks.sampling import"),
    ('"data/train_start_pool.npz"', '"outputs/p2/data/train_start_pool.npz"'),
    ('"data/train_goal_pool.npz"', '"outputs/p2/data/train_goal_pool.npz"'),
    ('"data/source_set.npz"', '"outputs/p2/data/source_set.npz"'),
    ('"openarm_hand"', '"panda_hand"'),
    ('"openarm_joint[1-7]"', '"panda_joint[1-7]"'),
    ("(openarm_hand)", "(panda_hand)"),
    ("OpenArm reach", "Franka reach"),
    ("class PolicyIKEnvCfg(OpenArmReachEnvCfg)", "class PolicyIKFrankaEnvCfg(FrankaReachEnvCfg)"),
    ("class PolicyIKEnvCfg_PLAY(OpenArmReachEnvCfg_PLAY)", "class PolicyIKFrankaEnvCfg_PLAY(FrankaReachEnvCfg_PLAY)"),
    ("scale=0.0625,\n", "scale=0.0625, ee_body_name=\"panda_hand\",\n"),
    ("def _configure(cfg, start_pool: str, goal_pool: str, train: bool) -> None:\n",
     "def _configure(cfg, start_pool: str, goal_pool: str, train: bool) -> None:\n    _franka_specific(cfg)\n"),
]
for a, b in subs:
    assert a in src, a
    src = src.replace(a, b)
src = src.replace('"""PolicyIK training and evaluation tasks built on the Franka reach task of openarm_isaac_lab."""',
                  '"""GENERATED by tools_local/policyik_franka/gen_franka_env_cfg.py from policyik_sim/tasks/env_cfg.py -- do not edit.\n'
                  'PolicyIK tasks on the Isaac Lab Franka reach task (P2)."""')
assert "openarm" not in src.lower(), [l for l in src.splitlines() if "openarm" in l.lower()]
extra = '''

def _franka_specific(cfg) -> None:
    """Franka-only differences (the OpenArm reach env already restricts these terms to its 7 arm joints)."""
    _sampling._ARM_EXPR = ["panda_joint[1-7]"]        # read at call time by reset_joints_from_pool
    def arm():   # one SceneEntityCfg per term (a shared instance cannot be resolved twice)
        return SceneEntityCfg("robot", joint_names=["panda_joint[1-7]"], preserve_order=True)
    cfg.observations.policy.joint_pos.params = {"asset_cfg": arm()}
    cfg.observations.policy.joint_vel.params = {"asset_cfg": arm()}
    cfg.rewards.joint_vel.params = {"asset_cfg": arm()}
    cfg.commands.ee_pose.ranges.pitch = (0.0, 0.0)     # unused: goals come from the pools
'''
src = src.replace("\n\ndef _configure(", extra + "\n\ndef _configure(", 1)
open("tools_local/policyik_franka/franka_env_cfg.py", "w").write(src)
print("ok")
