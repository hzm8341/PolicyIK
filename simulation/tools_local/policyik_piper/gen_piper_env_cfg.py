"""Generate piper_env_cfg.py from the official policyik_sim/tasks/env_cfg.py by mechanical substitution only
(robot names, base env, pool paths, absolute imports), plus a short Piper-specific block -- the same method as
policyik_franka/gen_franka_env_cfg.py. The PolicyIK observation/reward/action design stays byte-identical
otherwise; `diff` the two files to audit. Run from PolicyIK/simulation."""
src = open("policyik_sim/tasks/env_cfg.py").read()
subs = [
    ("from openarm.tasks.manager_based.openarm_manipulation.unimanual.reach.config.joint_pos_env_cfg import (\n"
     "    OpenArmReachEnvCfg,\n    OpenArmReachEnvCfg_PLAY,\n)",
     "from policyik_piper.piper_reach_cfg import PiperReachEnvCfg, PiperReachEnvCfg_PLAY"),
    ("from . import mdp", "from policyik_sim.tasks import mdp"),
    ("from .actions import", "from policyik_sim.tasks.actions import"),
    ("from .sampling import", "import policyik_sim.tasks.sampling as _sampling\nfrom policyik_sim.tasks.sampling import"),
    ('"data/train_start_pool.npz"', '"outputs/piper/data/train_start_pool.npz"'),
    ('"data/train_goal_pool.npz"', '"outputs/piper/data/train_goal_pool.npz"'),
    ('"data/source_set.npz"', '"outputs/piper/data/source_set.npz"'),
    ('"openarm_hand"', '"link6"'),
    ('"openarm_joint[1-7]"', '"joint[1-6]"'),
    ("(openarm_hand)", "(link6)"),
    ("OpenArm reach", "Piper reach"),
    ("class PolicyIKEnvCfg(OpenArmReachEnvCfg)", "class PolicyIKPiperEnvCfg(PiperReachEnvCfg)"),
    ("class PolicyIKEnvCfg_PLAY(OpenArmReachEnvCfg_PLAY)", "class PolicyIKPiperEnvCfg_PLAY(PiperReachEnvCfg_PLAY)"),
    ("scale=0.0625,\n", "scale=0.0625, ee_body_name=\"link6\",\n"),
    ("def _configure(cfg, start_pool: str, goal_pool: str, train: bool) -> None:\n",
     "def _configure(cfg, start_pool: str, goal_pool: str, train: bool) -> None:\n    _piper_specific(cfg)\n"),
]
for a, b in subs:
    assert a in src, a
    src = src.replace(a, b)
src = src.replace('"""PolicyIK training and evaluation tasks built on the Piper reach task of openarm_isaac_lab."""',
                  '"""GENERATED by tools_local/policyik_piper/gen_piper_env_cfg.py from policyik_sim/tasks/env_cfg.py -- do not edit.\n'
                  'PolicyIK tasks on the Piper reach environment (piper_reach_cfg.py)."""')
assert "openarm" not in src.lower(), [l for l in src.splitlines() if "openarm" in l.lower()]
extra = '''

def _piper_specific(cfg) -> None:
    """Piper-only differences: the arm terms are restricted to the 6 arm joints (the gripper joints stay out)."""
    _sampling._ARM_EXPR = ["joint[1-6]"]        # read at call time by reset_joints_from_pool
    def arm():   # one SceneEntityCfg per term (a shared instance cannot be resolved twice)
        return SceneEntityCfg("robot", joint_names=["joint[1-6]"], preserve_order=True)
    cfg.observations.policy.joint_pos.params = {"asset_cfg": arm()}
    cfg.observations.policy.joint_vel.params = {"asset_cfg": arm()}
    cfg.rewards.joint_vel.params = {"asset_cfg": arm()}
'''
src = src.replace("\n\ndef _configure(", extra + "\n\ndef _configure(", 1)
open("tools_local/policyik_piper/piper_env_cfg.py", "w").write(src)
print("ok")
